"""Make bonus/pm-book-gantt-tool.js from bonus/pm-book-gantt-tool.html.

The reader bonus (the Gantt chart tool) is not part of the public site: only the
Pages Function in functions/pm-book-bonus/download.js hands it out, after the
reader password is checked. The function imports the file as this JavaScript
module, so it is bundled with the function and never served as a static file.

    python3 tools/bonus_module.py

Run it again whenever bonus/pm-book-gantt-tool.html changes (tests check they match).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "bonus/pm-book-gantt-tool.html"
MODULE = ROOT / "bonus/pm-book-gantt-tool.js"

HEADER = "// Generated by tools/bonus_module.py from bonus/pm-book-gantt-tool.html; do not edit.\n"


def module_js(html: str) -> str:
    return HEADER + "export default " + json.dumps(html, ensure_ascii=False) + ";\n"


def main() -> None:
    MODULE.write_text(module_js(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"{MODULE.relative_to(ROOT)} を作成しました")


if __name__ == "__main__":
    main()
